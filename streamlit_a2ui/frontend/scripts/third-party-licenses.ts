/**
 * Writes streamlit_a2ui/THIRD_PARTY_LICENSES.txt: the license text of every
 * production npm dependency, since the minified bundle drops their headers.
 * Dependencies are read from package-lock.json (entries not marked dev).
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

type LockEntry = { version?: string; license?: string; dev?: boolean };
type Lock = { packages: Record<string, LockEntry> };

const root = fileURLToPath(new URL("..", import.meta.url));
const target = fileURLToPath(
  new URL("../../THIRD_PARTY_LICENSES.txt", import.meta.url),
);
const lock = JSON.parse(
  readFileSync(join(root, "package-lock.json"), "utf8"),
) as Lock;

const sections: string[] = [];
const paths = Object.keys(lock.packages)
  .filter(
    (path) => path.startsWith("node_modules/") && !lock.packages[path].dev,
  )
  .sort();
for (const path of paths) {
  const entry = lock.packages[path];
  const name = path.slice(path.lastIndexOf("node_modules/") + 13);
  const dir = join(root, path);
  const files = existsSync(dir)
    ? readdirSync(dir).filter((file) => /^(licen[cs]e|copying)/i.test(file))
    : [];
  const texts = files.map((file) =>
    readFileSync(join(dir, file), "utf8").trim(),
  );
  sections.push(
    [
      `${name}@${entry.version ?? "?"} (${entry.license ?? "license not declared"})`,
      texts.length > 0
        ? texts.join("\n\n")
        : "No license file is included in this package; see its declared license.",
    ].join("\n\n"),
  );
}

const rule = `\n\n${"-".repeat(72)}\n\n`;
writeFileSync(
  target,
  "Third-party software bundled in streamlit_a2ui/frontend/build\n" +
    "Generated by scripts/third-party-licenses.ts from package-lock.json." +
    rule +
    sections.join(rule) +
    "\n",
);
console.log(`wrote ${target} (${sections.length} packages)`);
